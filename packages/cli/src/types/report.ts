import type { CheckResult, Finding, Severity } from "./finding.js";
import type { ProtocolType } from "../adapters/types.js";
import type { ChamberReachabilityResult } from "../core/chamber-runtime.js";

/**
 * Information about a tool/function/endpoint exposed by the target.
 */
export interface ToolInfo {
  name: string;
  description?: string;
  inputSchema: Record<string, unknown>;
  annotations?: {
    readOnlyHint?: boolean;
    destructiveHint?: boolean;
    idempotentHint?: boolean;
    openWorldHint?: boolean;
    title?: string;
  };
  /** Protocol that exposed this tool (e.g., "mcp", "openai-functions") */
  sourceProtocol?: ProtocolType;
  /** Original protocol-specific type (e.g., "function", "tool", "action") */
  nativeType?: string;
  /** HTTP method if applicable (REST/GraphQL adapters) */
  httpMethod?: string;
  /** Endpoint path if applicable */
  endpointPath?: string;
}

/**
 * Information about a resource exposed by the target.
 */
export interface ResourceInfo {
  uri: string;
  name: string;
  description?: string;
  mimeType?: string;
}

/**
 * Information about a prompt template exposed by the target.
 */
export interface PromptInfo {
  name: string;
  description?: string;
  arguments?: Array<{
    name: string;
    description?: string;
    required?: boolean;
  }>;
}

/**
 * Capabilities discovered from the target server/endpoint.
 */
export interface ServerCapabilities {
  /** Server identification */
  serverInfo: {
    name: string;
    version: string;
  };
  /** Protocol version negotiated */
  protocolVersion: string;
  /** Capabilities declared by the server */
  capabilities: Record<string, unknown>;
  /** All tools exposed by the server */
  tools: ToolInfo[];
  /** All resources exposed by the server */
  resources: ResourceInfo[];
  /** All prompts exposed by the server */
  prompts: PromptInfo[];
  /** Protocol used to discover these capabilities */
  protocol?: ProtocolType;
}

/**
 * Summary statistics for a scan report.
 */
export interface ReportSummary {
  /** Total number of checks run */
  totalChecks: number;
  /** Checks passed */
  passed: number;
  /** Checks with warnings */
  warnings: number;
  /**
   * Checks that returned FAIL status.
   * NOTE: This is NOT the same as the number of findings.
   * A single finding may correspond to multiple failed checks, and some
   * findings are generated by modules that do not produce per-check entries.
   * Use `findingsBySeverity` for finding counts.
   */
  checksWithFailStatus: number;
  /** Checks skipped */
  skipped: number;
  /** Checks errored */
  errors: number;
  /** Count of deduplicated findings by severity */
  findingsBySeverity: Record<Severity, number>;
  /**
   * Security score after flooring at 0 (0–100).
   * Use this for grading and display.
   */
  securityScore: number;
  /**
   * Raw security score before the 0-floor is applied.
   * Can be negative when CRITICAL findings are numerous.
   * Use rawScore to distinguish between targets that both score 0:
   * a target at rawScore=-62 is far worse than rawScore=-3.
   */
  rawScore: number;
  /**
   * Total penalty points deducted from 100 (= 100 - rawScore).
   * Useful for normalised comparisons and the paper's regression analysis.
   */
  penaltyPoints: number;
}

/**
 * Module execution result within a report.
 */
export interface ModuleResult {
  /** Module identifier */
  moduleId: string;
  /** Module name */
  moduleName: string;
  /** Module version */
  moduleVersion: string;
  /** Duration in milliseconds */
  durationMs: number;
  /** Check results from this module */
  checks: CheckResult[];
  /** Findings from this module */
  findings: Finding[];
  /** Error if the module crashed */
  error?: string;
}

/**
 * Transport configuration used for the scan.
 */
export interface TransportConfig {
  type: "stdio" | "streamable-http" | "http" | "grpc" | "websocket";
  command?: string;
  args?: string[];
  url?: string;
  /** Protocol adapter used */
  protocol?: ProtocolType;
}

/**
 * Complete scan report.
 */
export interface ScanReport {
  /** Report version for forward compatibility */
  version: "1.0.0";
  /** Unique report identifier */
  id: string;
  /** Timestamp of the scan (ISO 8601) */
  timestamp: string;
  /** Duration of the entire scan in milliseconds */
  durationMs: number;
  /** toolsurf CLI version */
  cliVersion: string;
  /**
   * Git commit hash of the scanner build that produced this report.
   * Allows exact reproduction from source. "unknown" if git is unavailable at runtime.
   * (ref: INSTRUMENT-HARDENING-REPORT §REPRO item #09)
   */
  scannerCommit: string;
  /**
   * Effective scan mode used for this run after target-profile enforcement.
   * Legacy reports may contain "active"/"passive"; current reports prefer
   * "passive-only", "safe-active", or "full-active".
   */
  scanMode?: "active" | "passive" | import("../core/target-profile.js").ScanMode;

  /** Transport configuration used */
  transport: TransportConfig;
  /** Server capabilities discovered */
  server: ServerCapabilities;
  /** Results from each module */
  modules: ModuleResult[];
  /** All findings aggregated */
  findings: Finding[];
  /** Report summary and score */
  summary: ReportSummary;
  /** Multi-axis risk profile for research use (5 dimensions + composite) */
  riskProfile?: import("../core/scorer.js").RiskProfile;
  /**
   * Scoring formula version used to compute riskProfile and summary.
   * Sourced from SCORING_FORMULA_VERSION constant in scorer.ts.
   * Allows historical scan results to declare which formula produced them.
   * Example: "v4.0"
   */
  scoringFormulaVersion?: string;

  /**
   * Calibration status of this scan output.
   * "PRE-CALIBRATION" = instrument not yet validated against anchor fixtures.
   * "CALIBRATED" = BENCHMARK_FLOOR, BENCHMARK_CEILING, and sensitivity analysis pass.
   * Default: "PRE-CALIBRATION" until CI calibration gate passes.
   * (ref: INSTRUMENT-HARDENING-REPORT §REPRO item #10)
   */
  calibrationStatus?: "PRE-CALIBRATION" | "CALIBRATED";

  /**
   * Provenance block for W3C PROV-DM compliance and IEEE S&P artifact evaluation.
   * Contains all fields needed to reproduce the exact scan environment.
   * (ref: Research Plan §Topic 9)
   */
  provenance?: {
    /** CLI invocation flags (e.g. ["--active", "--research-json"]) */
    cliFlags: string[];
    /** Deterministic seed for active fuzzing reproducibility (if applicable) */
    deterministicSeed?: string;
    /** SHA-256 hash of scan configuration (flags, modules, thresholds) — enables mechanical comparison of two runs */
    configHash?: string;
    /** Docker image digest (sha256) if running inside a container */
    dockerDigest?: string;
    /** Node.js / Bun runtime version */
    runtimeVersion: string;
    /** OS platform and arch */
    platform: string;
    /** Selected environment variables relevant to scan behavior */
    envSnapshot: Record<string, string>;
  };

  /** TOFU schema hash — SHA-256 of canonical tool schemas for rug-pull detection on re-scan */
  schemaHash?: {
    schemaHash: string;
    toolHashes: Record<string, string>;
    toolCount: number;
  };
  /** PEAV pre-flight analysis results (passive evidence found before active fuzzing) */
  peavReport?: import("../core/peav.js").PeavReport;
  /**
   * Detonation chamber evidence summary — populated when --chamber-run-dir
   * is set. Mirrors the terminal `💥 Detonation Chamber` panel for JSON
   * consumers (CI dashboards, third-party reporters, vendor disclosure
   * pipelines). Only the chamber-evidence and active-fuzzer modules write
   * to this field.
   */
  chamberSummary?: {
    runDir: string;
    networkName?: string;
    captureRoot: string;
    captures: {
      http: { count: number; capturePath?: string; sample?: unknown };
      dns: { count: number; capturePath?: string; sample?: unknown };
      smtp: { count: number; capturePath?: string; sample?: unknown };
      metadata: { count: number; capturePath?: string; sample?: unknown };
      netflow: { count: number; capturePath?: string; sample?: unknown };
    };
    /** Active-fuzzer chamber-canary callbacks. Each row is a confirmed
     *  exfiltration: tool sent a payload that landed at a chamber sink. */
    confirmedExfil: Array<{
      findingId: string;
      tool: string;
      paramName?: string;
      sink: "http" | "dns" | "smtp" | "metadata";
      payload: string;
      payloadVariant?: string;
      canary: string;
    }>;
    /** IPI relay hits — strongest evidence: chamber's poisoned response
     *  was echoed back into the agent context. */
    ipiRelays: Array<{
      tool: string;
      paramName?: string;
      probeUrl: string;
      poisonToken: string;
      preservedFullPrompt: boolean;
      excerpt: string;
    }>;
    /** Headline severity counts for chamber-only findings. */
    severityCounts: { critical: number; high: number; medium: number; low: number };
  };
  /**
   * Result of the pre-active chamber healthcheck. Vendor disclosure export
   * requires `verified=true`; otherwise chamber-backed findings are treated
   * as non-disclosure-grade until a target-to-chamber path is proven.
   */
  chamberReachability?: ChamberReachabilityResult;
  /**
   * Synthesized attack paths built from findings + chamber evidence. This is
   * the operator-facing "what actually happened" layer: completed, partial,
   * and blocked kill chains.
   */
  killChainSummary?: import("../core/kill-chain.js").KillChainSummary;
  /**
   * Persisted chamber proof bundle. The JSONL file binds proof IDs to concrete
   * artifact paths, SHA-256 hashes, marker line ranges, and missing-artifact
   * counts. This is the vendor-grade proof ledger for chamber-backed reports.
   */
  chamberProofBundle?: import("../core/chamber-proofs.js").ChamberProofBundleSummary;
  /**
   * Egress matrix — auditor-grade rigid grid summarizing which network
   * destination classes were reached via which chamber sinks. Built from
   * AF-CHAMBER-* / CHAMBER-* findings; one row per destination class, one
   * column per sink, cells = {verified, canaries, variants}.
   */
  egressMatrix?: import("../core/egress-matrix.js").EgressMatrix;
  /** Optional compliance summary */
  compliance?: {
    nist: Record<string, number>;
    soc2: Record<string, number>;
    asvs: Record<string, number>;
    hipaa: Record<string, number>;
    pciDss: Record<string, number>;
    iso27001: Record<string, number>;
    fedramp: Record<string, number>;
    gdpr: Record<string, number>;
    mappedFindings: number;
    unmappedFindings: number;
  };
}
